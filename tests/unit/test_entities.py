def test_citation_source_valid_and_bounds():
    """Verify CitationSource checks page number and relevance score bounds."""
    citation = CitationSource(
        document_name="nvda_10k_2024.pdf",
        page_number=42,
        is_table=True,
        excerpt="| Data Center Revenue | $18.4B |",
        relevance_score=0.96,
    )
    assert citation.document_name == "nvda_10k_2024.pdf"
    assert citation.page_number == 42
    assert citation.is_table is True
    assert citation.relevance_score == 0.96

    # Out of range relevance score
    with pytest.raises(ValidationError):
        CitationSource(
            document_name="nvda_10k_2024.pdf",
            page_number=1,
            excerpt="Some text",
            relevance_score=1.5,
        )

    with pytest.raises(ValidationError):
        CitationSource(
            document_name="nvda_10k_2024.pdf",
            page_number=0,  # Page 0 invalid
            excerpt="Some text",
            relevance_score=0.5,
        )


def test_analysis_report_valid_and_defaults():
    """Verify AnalysisReport satisfies full audit trail contract."""
    citation = CitationSource(
        document_name="apple_10k_2023.pdf",
        page_number=22,
        is_table=False,
        excerpt="Total net sales for fiscal 2023 were $383,285 million.",
        relevance_score=0.95,
    )
    metric = FinancialMetric(
        name="Net Sales",
        value=383285.0,
        unit="USD Millions",
        period="FY2023",
        context_sentence="Total net sales for fiscal 2023 were $383,285 million.",
    )

    report = AnalysisReport(
        query="What was Apple's total net sales in FY2023?",
        executive_summary="Apple reported total net sales of $383,285 million in fiscal year 2023, reflecting a slight contraction from FY2022.",
        extracted_metrics=[metric],
        citations=[citation],
        audit_warnings=["Notice: Net sales declined by 2.8% year-over-year."],
        confidence_score=0.97,
        model_used="llama-3.3-70b-versatile",
        processing_time_ms=482.5,
    )

    assert report.confidence_score == 0.97
    assert len(report.citations) == 1
    assert len(report.extracted_metrics) == 1
    assert report.model_used == "llama-3.3-70b-versatile"
    assert report.created_at.tzinfo == UTC


def test_analysis_report_requires_citations_and_summary_length():
    """Verify AnalysisReport rejects reports without citations or with trivial summary."""
    citation = CitationSource(
        document_name="test.pdf",
        page_number=1,
        excerpt="Sample excerpt",
        relevance_score=0.9,
    )

    # Empty citations rejected
    with pytest.raises(ValidationError):
        AnalysisReport(
            query="Sample query?",
            executive_summary="Valid summary text that meets length requirements.",
            citations=[],  # Min length 1
            confidence_score=0.8,
        )

    # Summary too short (< 10 chars)
    with pytest.raises(ValidationError):
        AnalysisReport(
            query="Sample query?",
            executive_summary="Short",  # Min length 10
            citations=[citation],
            confidence_score=0.8,
        )


