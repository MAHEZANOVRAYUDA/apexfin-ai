"""
Unit tests for pure domain entities in ApexFin AI.
Verifies contract boundaries, constraints, and audit metadata.
"""

from datetime import UTC

import pytest
from pydantic import ValidationError

from src.domain.entities import (
    AnalysisReport,
    ChunkMetadata,
    CitationSource,
    DocumentChunk,
    DocumentIngestionResult,
    FinancialMetric,
)


def test_chunk_metadata_valid():
    """Verify ChunkMetadata accepts valid coordinates and defaults."""
    meta = ChunkMetadata(
        document_id="doc-apple-2023",
        document_name="apple_10k_2023.pdf",
        page_number=14,
        chunk_index=3,
        is_table=True,
        table_id="tbl-page14-01",
        section_header="Item 7. Management's Discussion and Analysis",
    )
    assert meta.document_id == "doc-apple-2023"
    assert meta.page_number == 14
    assert meta.chunk_index == 3
    assert meta.is_table is True
    assert meta.table_id == "tbl-page14-01"


def test_chunk_metadata_invalid_page():
    """Verify page_number must be >= 1 (1-indexed for financial auditability)."""
    with pytest.raises(ValidationError):
        ChunkMetadata(
            document_id="doc-1",
            document_name="test.pdf",
            page_number=0,  # Invalid: 0 is not allowed
            chunk_index=0,
        )


def test_chunk_metadata_invalid_chunk_index():
    """Verify chunk_index must be >= 0."""
    with pytest.raises(ValidationError):
        ChunkMetadata(
            document_id="doc-1",
            document_name="test.pdf",
            page_number=1,
            chunk_index=-1,  # Invalid: negative index
        )


def test_document_chunk_uuid_and_scoring():
    """Verify DocumentChunk auto-generates UUID and handles multi-arm scores."""
    meta = ChunkMetadata(
        document_id="doc-nvda-2024",
        document_name="nvda_q3_2024.pdf",
        page_number=5,
        chunk_index=0,
    )
    chunk = DocumentChunk(
        content="| Revenue | $35,082M |\n| Gross Margin | 74.6% |",
        metadata=meta,
        dense_score=0.884,
        sparse_score=14.2,
        rrf_score=0.032,
        rerank_score=0.941,
    )
    assert len(chunk.chunk_id) > 10
    assert chunk.content.startswith("| Revenue")
    assert chunk.dense_score == 0.884
    assert chunk.rerank_score == 0.941


def test_document_chunk_empty_content_rejected():
    """Verify chunk rejects empty content."""
